"""Generate persistent storage configuration inside the mounted target."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from uuid import UUID

from .btrfs import BTRFS_SUBVOLUMES
from .command import CommandRunner
from .encryption import (
    MACHINE_KEY_PATH, ROOT_BOOT_MAPPING, SWAP_BOOT_MAPPING,
    SWAP_CIPHER, SWAP_KEY_BITS, install_machine_key,
)
from .model import EncryptionMode, Filesystem
from .steps import FailurePolicy, InstallContext


ENCRYPTED_SLEEP_POLICY = (
    "[Sleep]\n"
    "AllowHibernation=no\n"
    "AllowHybridSleep=no\n"
    "AllowSuspendThenHibernate=no\n"
)
ENCRYPTED_SLEEP_PATH = "etc/systemd/sleep.conf.d/40-anduinos-encrypted-install.conf"
ENCRYPTED_GRUB_PATH = "etc/default/grub.d/40-anduinos-encryption.cfg"


def encrypted_grub_defaults(luks_uuid: str) -> str:
    # The flag is exported because grub-mkconfig executes 10_linux as a child.
    # Both defaults and their UUID live inside encrypted root, never on ESP.
    return (
        "# Installed encrypted root; preserve the upstream Linux menu generator.\n"
        "GRUB_ENABLE_CRYPTODISK=y\n"
        "export GRUB_ANDUINOS_CRYPT_HANDOFF=y\n"
        "GRUB_DISABLE_LINUX_UUID=false\n"
        "GRUB_FORCE_PARTUUID=\n"
        f'GRUB_CMDLINE_LINUX="${{GRUB_CMDLINE_LINUX:-}} rd.luks.uuid=luks-{luks_uuid}"\n'
    )


@dataclass
class ConfigureStorageStep:
    runner: CommandRunner
    id: str = "configure-storage"
    title: str = "Configure persistent filesystems and swap"
    failure_policy: FailurePolicy = FailurePolicy.FATAL
    progress_weight: int = 2
    destructive: bool = False

    def preflight(self, context: InstallContext) -> None:
        self.runner.require_commands(("blkid",))

    def execute(self, context: InstallContext) -> None:
        target = _target(context)
        devices = context.values.get("filesystem_devices", context.values["partition_devices"])
        uuids = {
            name: self.runner.run(
                ("blkid", "-s", "UUID", "-o", "value", device),
                timeout=10,
            ).stdout.strip()
            for name, device in devices.items()
            if name in {"root", "efi-system", "swap"}
            and not (name == "swap" and context.plan.encrypted_swap)
        }
        missing = sorted(name for name, value in uuids.items() if not value)
        if missing:
            raise RuntimeError(
                "Missing filesystem UUID: " + ", ".join(missing)
            )

        if context.plan.storage.filesystem is Filesystem.BTRFS:
            root_lines = "".join(
                f"UUID={uuids['root']} {subvolume.mount_point} btrfs "
                f"{subvolume.mount_options(context.plan.storage.btrfs_compression)} 0 0\n"
                for subvolume in BTRFS_SUBVOLUMES
            )
        else:
            filesystem = context.plan.storage.filesystem
            pass_number = 0 if filesystem is Filesystem.XFS else 1
            root_lines = (
                f"UUID={uuids['root']} / {filesystem.value} "
                f"defaults,noatime 0 {pass_number}\n"
            )

        swap_line = (
            f"UUID={uuids['swap']} none swap "
            f"sw,pri={context.plan.swap.disk_priority} 0 0\n"
            if "swap" in uuids
            else ""
        )
        if context.plan.encrypted_swap:
            # A fresh random swap key also creates a fresh filesystem UUID.
            # Refer to its stable mapper, never the installation-time UUID.
            swap_line = (
                f"/dev/mapper/{SWAP_BOOT_MAPPING} none swap "
                f"sw,pri={context.plan.swap.disk_priority} 0 0\n"
            )
        fstab = (
            "# /etc/fstab generated by AnduinOS Installer\n"
            f"{root_lines}"
            f"UUID={uuids['efi-system']} /boot/efi vfat defaults,noatime 0 1\n"
            f"{swap_line}"
        )
        etc = target / "etc"
        etc.mkdir(parents=True, exist_ok=True)
        (etc / "fstab").write_text(fstab, encoding="utf-8")

        crypttab = ""
        if context.plan.storage.encryption is EncryptionMode.LUKS2:
            raw = context.values["partition_devices"]
            luks_uuid = str(UUID(self.runner.run(
                ("cryptsetup", "luksUUID", raw["root"]), timeout=10,
            ).stdout.strip()))
            if luks_uuid == uuids["root"]:
                raise RuntimeError("LUKS and inner filesystem identities must differ")
            crypttab = f"{ROOT_BOOT_MAPPING} UUID={luks_uuid} none luks,x-initrd.attach\n"
            context.values["root_luks_uuid"] = luks_uuid
            context.values["root_filesystem_uuid"] = uuids["root"]
            if context.plan.encrypted_swap:
                partuuid = str(UUID(self.runner.run(
                    ("blkid", "-s", "PARTUUID", "-o", "value", raw["swap"]),
                    timeout=10,
                ).stdout.strip()))
                crypttab += (
                    f"{SWAP_BOOT_MAPPING} PARTUUID={partuuid} /dev/urandom "
                    f"swap,cipher={SWAP_CIPHER},size={SWAP_KEY_BITS}\n"
                )
            install_machine_key(context, self.runner, target)
            grub_defaults = target / ENCRYPTED_GRUB_PATH
            grub_defaults.parent.mkdir(parents=True, exist_ok=True)
            grub_defaults.write_text(encrypted_grub_defaults(luks_uuid), encoding="utf-8")
            # Random-key swap cannot resume an old memory image. Even the
            # explicit plaintext-swap exception does not enable hibernation in
            # this first encrypted-installation policy.
            sleep_policy = target / ENCRYPTED_SLEEP_PATH
            sleep_policy.parent.mkdir(parents=True, exist_ok=True)
            sleep_policy.write_text(ENCRYPTED_SLEEP_POLICY, encoding="utf-8")
        (etc / "crypttab").write_text(crypttab, encoding="utf-8")
        context.values["target_crypttab"] = crypttab

        # Keep zram declarative and explicit. This is the format consumed by
        # anduinos-swap-config; omitting a fixed size preserves 50%-of-RAM.
        defaults = etc / "default"
        defaults.mkdir(parents=True, exist_ok=True)
        (defaults / "anduinos-zram").write_text(
            "ZRAM_ENABLED=yes\n"
            f"ZRAM_ALGORITHM={context.plan.swap.zram_algorithm}\n"
            f"ZRAM_PRIORITY={context.plan.swap.zram_priority}\n",
            encoding="utf-8",
        )

    def verify(self, context: InstallContext) -> None:
        target = _target(context)
        fstab = (target / "etc/fstab").read_text(encoding="utf-8")
        required = ["/boot/efi vfat", "UUID=", " / "]
        if context.plan.storage.swap_size_mib:
            required.append(" none swap ")
        missing = [value for value in required if value not in fstab]
        if missing:
            raise RuntimeError("Generated fstab failed verification")
        if context.plan.storage.swap_size_mib and (
            f"pri={context.plan.swap.disk_priority}" not in fstab
        ):
            raise RuntimeError("Disk swap priority is missing from fstab")
        if not context.plan.storage.swap_size_mib and " none swap " in fstab:
            raise RuntimeError("Unexpected disk swap entry in fstab")
        zram = (target / "etc/default/anduinos-zram").read_text(
            encoding="utf-8"
        )
        required_zram = (
            "ZRAM_ENABLED=yes",
            f"ZRAM_ALGORITHM={context.plan.swap.zram_algorithm}",
            f"ZRAM_PRIORITY={context.plan.swap.zram_priority}",
        )
        if any(value not in zram for value in required_zram):
            raise RuntimeError("Generated zram configuration failed verification")
        if (target / "etc/crypttab").read_text() != context.values["target_crypttab"]:
            raise RuntimeError("Generated crypttab failed verification")
        if context.plan.storage.encryption is EncryptionMode.LUKS2:
            defaults = encrypted_grub_defaults(context.values["root_luks_uuid"])
            if (target / ENCRYPTED_GRUB_PATH).read_text() != defaults:
                raise RuntimeError("Encrypted GRUB configuration failed verification")
            if (target / ENCRYPTED_SLEEP_PATH).read_text() != ENCRYPTED_SLEEP_POLICY:
                raise RuntimeError("Encrypted installation must disable hibernation")
            key = target / MACHINE_KEY_PATH
            if key.is_symlink() or key.stat().st_size != 64 or key.stat().st_mode & 0o777 != 0o600:
                raise RuntimeError("The installed machine credential is invalid")
            if context.plan.encrypted_swap and f"/dev/mapper/{SWAP_BOOT_MAPPING} none swap" not in fstab:
                raise RuntimeError("Encrypted swap must use its persistent mapper name")

    def cleanup(self, context: InstallContext) -> None:
        return None


def _target(context: InstallContext) -> Path:
    target = context.values.get("target")
    if not isinstance(target, Path):
        raise RuntimeError("Target filesystem is not mounted")
    return target
